from hashlib import sha256
import math
import re
from typing import Protocol

import httpx

from app.config import get_settings


class EmbeddingProvider(Protocol):
    dimension: int

    def embed(self, text: str) -> list[float]:
        ...


class HashEmbeddingProvider:
    """Deterministic, dependency-free embedding provider for local development.

    This is deliberately an offline baseline, not a replacement for a semantic
    model. The provider interface allows an LLM or sentence-transformer
    embedding provider to be introduced without changing the knowledge schema.
    """

    def __init__(self, dimension: int = 128):
        if dimension < 8:
            raise ValueError("Embedding dimension must be at least 8")
        self.dimension = dimension

    def embed(self, text: str) -> list[float]:
        tokens = re.findall(r"[a-z0-9][a-z0-9+#.-]*", text.lower())
        vector = [0.0] * self.dimension
        for token in tokens:
            digest = sha256(token.encode("utf-8")).digest()
            index = int.from_bytes(digest[:4], "big") % self.dimension
            sign = 1.0 if digest[4] % 2 else -1.0
            vector[index] += sign

        magnitude = math.sqrt(sum(value * value for value in vector))
        if magnitude == 0:
            return vector
        return [value / magnitude for value in vector]


class OllamaEmbeddingProvider:
    """Semantic embeddings generated by the configured local Ollama model."""

    def __init__(
        self,
        *,
        base_url: str | None = None,
        model: str | None = None,
        timeout_seconds: float | None = None,
    ):
        settings = get_settings()
        self.base_url = (base_url or settings.ollama_base_url).rstrip("/")
        self.model = model or settings.ollama_embedding_model
        self.timeout_seconds = timeout_seconds or settings.ollama_timeout_seconds
        self.dimension = 0

    def embed(self, text: str) -> list[float]:
        try:
            response = httpx.post(
                f"{self.base_url}/api/embed",
                json={"model": self.model, "input": text},
                timeout=self.timeout_seconds,
            )
            response.raise_for_status()
            embeddings = response.json().get("embeddings", [])
            if not embeddings or not embeddings[0]:
                raise ValueError("Ollama returned an empty embedding")
            vector = [float(value) for value in embeddings[0]]
            self.dimension = len(vector)
            return vector
        except (httpx.HTTPError, TypeError, ValueError) as exc:
            raise RuntimeError("Ollama embedding service is unavailable") from exc


def cosine_similarity(left: list[float], right: list[float]) -> float:
    if len(left) != len(right):
        raise ValueError("Embedding vectors must have the same dimension")
    return sum(a * b for a, b in zip(left, right, strict=True))
